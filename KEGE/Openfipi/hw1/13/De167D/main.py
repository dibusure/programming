# нам надо, чтобы 12 обязательно было в траектории
# так давай просто посмотрим количество путей от 19 до 12, а потом от 12 до трёх — нам надо будет их перемножить, что логично

def f(s, e): # as in start, end
    if s == e:
        return 1
    if s < e or s == 9:
        return 0

    return f(s-1, e) + f(s-3, e) + f(s//2, e)

print(f(19, 12) * f(12, 3))
