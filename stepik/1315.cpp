// шест высотой h метров, улитка днём поднимается на а метров, ночью опускается на b метров, когда она доползёт?
#include <iostream>

int main()
{
    int h = 0, a = 0, b = 0, t = 0;
    scanf("%d %d %d", &h, &a, &b);

    // h = t*a - b*(t-1) = t(a-b) + b; t = (h-b)/(a-b)
    t = (h - b + a - b - 1) / (a - b); // ДЕЛЕНИЕ С ОКРУГЛЕНИЕМ ВВЕРХ: А /* B = (A+B-1)/B
    printf("%d\n", t);

    return 0;
}